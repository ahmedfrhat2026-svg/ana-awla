/// فحص أمان محلي بالكامل — لا يُرسل أي نص إلى أي خادم أبدًا.
///
/// عند وجود إشارات واضحة لإيذاء النفس في نص حر، يعرض التطبيق رسالة داعمة
/// عامة تشجّع على التواصل الفوري مع شخص موثوق أو خدمة طوارئ محلية.
/// التطبيق لا يشخّص ولا يعالج ولا يقدّم محتوى دينيًا كبديل عن المساعدة.
library;

const List<String> _selfHarmSignals = [
  'انتحار',
  'انتحر',
  'اقتل نفسي',
  'أقتل نفسي',
  'اذي نفسي',
  'أذي نفسي',
  'إيذاء نفسي',
  'عايز اموت',
  'عايز أموت',
  'نفسي اموت',
  'نفسي أموت',
  'مش عايز اعيش',
  'مش عايز أعيش',
];

/// هل يحتوي النص على إشارة واضحة لإيذاء النفس؟
bool containsSelfHarmSignal(String text) {
  final normalized = text.trim();
  if (normalized.isEmpty) return false;
  return _selfHarmSignals.any(normalized.contains);
}

